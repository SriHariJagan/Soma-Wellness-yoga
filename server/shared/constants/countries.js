const CODE_SET = new Set(COUNTRIES.map((c) => c.code));

export function isValidCountryCode(code) {
  return typeof code === 'string' && CODE_SET.has(code.trim().toUpperCase());
}

export function countryNameFor(code) {
  const up = String(code || '').trim().toUpperCase();
  return COUNTRIES.find((c) => c.code === up)?.name || '';
}
